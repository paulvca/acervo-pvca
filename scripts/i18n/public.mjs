export const translate = (lang, text) =>
  lang === "en"
    ? (en[text] ??
      (text.endsWith(" — Acervo PVCA")
        ? (en[text.split(" — ")[0]] ?? text.split(" — ")[0]) + " — Acervo PVCA"
        : text))
    : text;
export const preferredLanguage = (manual, languages = [], country) =>
  ["pt-BR", "en"].includes(manual)
    ? manual
    : country === "BR" ||
        String(languages[0] ?? "")
          .toLowerCase()
          .startsWith("pt")
      ? "pt-BR"
      : "en";
export function routePath(pathname, basePath = "/") {
  const prefix = basePath.replace(/\/$/, "");
  return (
    (prefix && (pathname === prefix || pathname.startsWith(prefix + "/"))
      ? pathname.slice(prefix.length)
      : pathname) || "/"
  );
}
export function languagePath(lang, pathname, basePath = "/") {
  const route =
    routePath(pathname, basePath).replace(/^\/en(?=\/|$)/, "") || "/";
  const prefix = basePath.replace(/\/$/, "");
  return (
    prefix +
    (lang === "en" ? "/en" : "") +
    (route.startsWith("/") ? route : "/" + route)
  );
}

export function countryHint(language, timeZone) {
  const brazilianZones = [
    "America/Noronha",
    "America/Belem",
    "America/Fortaleza",
    "America/Recife",
    "America/Araguaina",
    "America/Maceio",
    "America/Bahia",
    "America/Sao_Paulo",
    "America/Campo_Grande",
    "America/Cuiaba",
    "America/Santarem",
    "America/Porto_Velho",
    "America/Boa_Vista",
    "America/Manaus",
    "America/Eirunepe",
    "America/Rio_Branco",
  ];
  return language?.split("-")[1]?.toUpperCase() === "BR" ||
    brazilianZones.includes(timeZone)
    ? "BR"
    : undefined;
}
